"""Phase-3 decision rules and figure (docs/preregistration_phase3.md).

    python scripts/analyze_phase3.py
Writes results/phase3/summary.md, results/phase3/summary.json, figures/phase3_progressive.png.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import matplotlib.ticker  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
P2, P3, P1 = ROOT / "results" / "phase2", ROOT / "results" / "phase3", ROOT / "results" / "runs"
FIG = ROOT / "figures"
BITS = [32.0, 4.0, 1.58]
B_LABEL = {32.0: "float (bf16)", 4.0: "int4", 1.58: "ternary"}
COL = {32.0: "#2a78d6", 4.0: "#eb6834", 1.58: "#1baf7a"}
INK2, GRID, SURF, INK = "#52514e", "#e4e3df", "#fcfcfb", "#0b0b0b"

# arm -> (progressive result, baseline result, baseline-run json for its training horizon)
ARMS = {
    "P-mod7-local": (P3 / "extrap_prog_mod7_d64_T32_w4_N512.json", P2 / "extrap_mod7_tied_d64_T32_w4_N512.json",
                     P3 / "runs" / "prog_mod7_d64_T32_w4.json", P2 / "runs" / "mod7_tied_d64_T32_w4.json"),
    "P-mod7-global": (P3 / "extrap_prog_mod7_d64_T32_w0_N512.json", P2 / "extrap_mod7_tied_d64_T32_N512.json",
                      P3 / "runs" / "prog_mod7_d64_T32_w0.json", P1 / "mod7_tied_d64_T32.json"),
    "P-ca-local": (P3 / "runs" / "prog_ca110d64_d64_T32_w4.json", P2 / "runs" / "ca110d64_tied_d64_T32_w4.json",
                   P3 / "runs" / "prog_ca110d64_d64_T32_w4.json", P2 / "runs" / "ca110d64_tied_d64_T32_w4.json"),
}


def med(v):
    v = [x for x in v if x is not None]
    return statistics.median(v) if v else None


def passes_of(r):
    return [int(t) for t in r["models"][0]["eval"]] if "passes" not in r else r["passes"]


def curve(r, bits=None):
    ts = sorted(passes_of(r))
    ms = [m for m in r["models"] if bits is None or float(m["bits"]) == bits]
    return {t: med([m["eval"][str(t)]["n_star"]["0.9"] for m in ms if str(t) in m["eval"]]) for t in ts}


def load(p):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def verdicts(c_prog, c_base):
    out = {}
    if 32 in c_prog and c_prog[32]:
        later = [t for t in c_prog if t > 32]
        out["stable"] = all(c_prog[t] >= 0.9 * c_prog[32] for t in later)
        out["extrapolates"] = 128 in c_prog and c_prog[128] >= 2 * c_prog[32]
    if c_base and 128 in c_prog and 128 in c_base and c_base[128]:
        ratio = c_prog[128] / c_base[128]
        out["ratio_vs_base_128"] = ratio
        out["effect"] = "helps" if ratio >= 1.5 else ("hurts" if ratio <= 1 / 1.5 else "no clear effect")
    elif c_base and 128 in c_base and c_base[128] == 0 and c_prog.get(128):
        out["ratio_vs_base_128"], out["effect"] = float("inf"), "helps"
    return out


def main():
    plt.rcParams.update({"figure.facecolor": SURF, "axes.facecolor": SURF, "savefig.facecolor": SURF,
                         "axes.edgecolor": INK2, "axes.grid": True, "grid.color": GRID, "font.size": 10,
                         "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False,
                         "text.color": INK, "xtick.color": INK2, "ytick.color": INK2, "axes.labelcolor": INK})
    P3.mkdir(parents=True, exist_ok=True)
    summary, md = {}, ["# Phase 3 summary (generated by scripts/analyze_phase3.py)", "",
                       "Median n* over bit-widths and seeds at theta = 0.9; baseline = same recipe without the "
                       "progressive term.", "",
                       "| arm | progressive n* by test passes | baseline n* | stable | extrapolates | "
                       "effect at 128 passes (ratio) | horizon: progressive / baseline |",
                       "|---|---|---|---|---|---|---|"]
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.2), squeeze=False)
    for ax, (arm, (pp, bp, prun, brun)) in zip(axes[0], ARMS.items()):
        rp, rb = load(pp), load(bp)
        if rp is None:
            md.append(f"| {arm} | pending | | | | | |")
            continue
        cp, cb = curve(rp), (curve(rb) if rb else None)
        v = verdicts(cp, cb)
        hp, hb = load(prun), load(brun)
        hor = f"{(hp or {}).get('final_horizon')} / {(hb or {}).get('final_horizon')}"
        summary[arm] = {"progressive": cp, "baseline": cb, **v}
        fmt = lambda c: ", ".join(f"{t}: {x:g}" for t, x in c.items() if x is not None)  # noqa: E731
        md.append(f"| {arm} | {fmt(cp)} | {fmt(cb) if cb else '–'} | {v.get('stable')} | {v.get('extrapolates')} "
                  f"| {v.get('effect', '–')} ({v.get('ratio_vs_base_128', float('nan')):.2f}) | {hor} |")
        for r, ls, mk in ((rp, "-", "o"), (rb, "--", "s")):
            if r is None:
                continue
            for b in BITS:
                c = curve(r, b)
                ts = [t for t in c if c[t] is not None and t >= 8]
                ax.plot(ts, [max(c[t], 0.85) for t in ts], color=COL[b], ls=ls, marker=mk, markersize=4,
                        alpha=1.0 if ls == "-" else 0.7)
        ax.set_xscale("log", base=2)
        ax.set_yscale("log", base=2)
        for axis in (ax.xaxis, ax.yaxis):
            axis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:g}"))
        ax.axvline(32, color=INK2, lw=0.8, alpha=0.6)
        ax.set_title(arm, loc="left", fontsize=11)
        ax.set_xlabel("passes at test time (trained at 32)")
    axes[0][0].set_ylabel("n*")
    handles = [plt.Line2D([], [], color=COL[b], lw=2, label=B_LABEL[b]) for b in BITS]
    handles += [plt.Line2D([], [], color=INK2, ls="-", marker="o", label="progressive loss"),
                plt.Line2D([], [], color=INK2, ls="--", marker="s", label="baseline (no progressive term)")]
    fig.legend(handles=handles, loc="lower center", ncol=5, fontsize=8.5, bbox_to_anchor=(0.5, -0.01))
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    fig.savefig(FIG / "phase3_progressive.png", dpi=160)
    plt.close(fig)
    (P3 / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (P3 / "summary.json").write_text(json.dumps(summary, indent=1, default=str), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
